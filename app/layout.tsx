import type { Metadata } from "next";
import localFont from "next/font/local";
import { cookies } from "next/headers";
import { Providers } from "@/app/providers";
import { AUTH_TOKEN_KEY } from "@/lib/auth/constants";
import "./globals.css";

const univers = localFont({
  src: [
    { path: "../assets/univers/UniversLight.ttf", weight: "300", style: "normal" },
    { path: "../assets/univers/UniversRegular.ttf", weight: "400", style: "normal" },
    { path: "../assets/univers/UniversBold.ttf", weight: "700", style: "normal" },
  ],
  variable: "--font-univers",
  display: "swap",
});

const universCondensed = localFont({
  src: "../assets/univers/UniversCnBold.ttf",
  weight: "700",
  style: "normal",
  variable: "--font-univers-condensed",
  display: "swap",
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const cookieStore = await cookies();
  const initialHasToken = Boolean(cookieStore.get(AUTH_TOKEN_KEY)?.value);

  return (
    <html lang="en" className={`${univers.variable} ${universCondensed.variable} h-full antialiased`}>
      <body className="min-h-full flex flex-col">
        <Providers initialHasToken={initialHasToken}>{children}</Providers>
      </body>
    </html>
  );
}
